// Builds site/scenarios.js: a small index of the playground's scenarios (id,
// title, group, level, story), so the first screen can show the incident count,
// the path's lab links and the on-call shift before playground.js has loaded.
// Run with: node tools/build-scenarios.js   (tests/check_playground.js keeps it in sync)
"use strict";
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const file = path.join(root, "site/scenarios.js");

function render() {
  global.window = {};
  for (const f of ["site/hcl.js", "site/playground.js"]) {
    delete require.cache[path.join(root, f)];
    require(path.join(root, f));
  }
  const list = window.TQSim.SCENARIOS.map((s) => ({ id: s.id, title: s.title, group: s.group, level: s.level, story: s.story }));
  return `// Generated by tools/build-scenarios.js from site/playground.js. Do not edit.
"use strict";
window.TRACK_SCENARIOS = ${JSON.stringify(list, null, 1)};
`;
}

if (require.main === module) {
  fs.writeFileSync(file, render());
  console.log(`wrote ${path.relative(root, file)}`);
}
module.exports = { render, file };
